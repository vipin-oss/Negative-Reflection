"""
Generate the independent row-by-row comparison report for task 1R (P0-2).

This emits a table with one row per exported row, comparing every numeric field
against an independent recomputation. It is generated rather than written by
hand so the report cannot drift from the data it describes.

Reproduce:
    cd code && python3 -m scattering.compare_report
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

import mpmath as mp

sys.path.insert(0, ".")

import foundation_checks as fc                                    # noqa: E402
from scattering.modal import classify_mode                         # noqa: E402
from scattering.nullspace import null_vector                       # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
INV = ROOT / "validation" / "phase_02a_modal_inventory_v2.csv"
OLD = ROOT / "validation" / "phase_02a_modal_inventory.csv"
OUT = ROOT / "reports" / "PHASE_02A_TASK1R_ROW_COMPARISON.md"

DPS = 60
F_HZ = 1e6


def _bank(mat, theta):
    w = 2 * mp.pi * F_HZ
    k = w * mp.sin(mp.radians(theta)) / 4000.0
    m = fc.material_from_table(mat)
    roots = [mp.mpc(z) for z in m.xi_roots(k, w)]
    out = []
    for xi in roots:
        a = null_vector(fc.M_mp(m, k, xi, w), DPS)["vector"]
        jz = fc.flux_z_mp(m, k, xi, w, a)
        out.append((xi, jz, classify_mode(m, k, xi, w, a, jz=jz)))
    return out


#: abbreviated radiation labels for the table header
_SHORT = {
    "DECAYS_TOWARD_PLUS_Z": "decay +z",
    "DECAYS_TOWARD_MINUS_Z": "decay −z",
    "TRAVELS_TOWARD_PLUS_Z": "travel +z",
    "TRAVELS_TOWARD_MINUS_Z": "travel −z",
    "NONE": "none",
}


def _short(rad):
    return _SHORT.get(rad, rad)


def _cmp(exported, exact, rel="1e-9"):
    try:
        e = mp.mpf(exported)
    except Exception:                                              # noqa: BLE001
        return False
    if exact == 0:
        return abs(e) == 0
    return abs(e - exact) / abs(exact) <= mp.mpf(rel)


def main():
    mp.mp.dps = DPS
    rows = list(csv.DictReader(INV.open()))
    old = {}
    if OLD.exists():
        for r in csv.DictReader(OLD.open()):
            old[(r["material"], r["theta_deg"], r["branch"])] = r

    lines = [
        "# Phase 2A Task 1R — Independent Row-by-Row Comparison",
        "",
        "Generated by `cd code && python3 -m scattering.compare_report`.",
        "Do not edit by hand: this file is regenerated from the data and the",
        "independent recomputation, so it cannot drift from either.",
        "",
        f"- Corrected artifact: `{INV.relative_to(ROOT)}`",
        f"- Invalidated artifact: `{OLD.relative_to(ROOT)}`",
        f"- Rows compared: {len(rows)}",
        f"- Oracle: independent recomputation at {DPS} dps — root bank, "
        f"polynomial evaluation, recomputed flux for each row's own "
        f"eigenvector, classification re-derived from the root.",
        "",
        "`Re/Im/|xi|/J_z` columns show **MATCH** or the exported value when it",
        "disagrees. `OLD` shows what the invalidated task-1 file contained for",
        "the same row, to make the P0-1 contamination visible.",
        "",
        "| material | θ | br | Re ξ | Im ξ | abs ξ | J_z | class | rad | adm | "
        "role | OLD Re ξ | OLD J_z |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    bad = 0
    for r in rows:
        mat, theta, br = r["material"], float(r["theta_deg"]), int(r["branch"])
        xi, jz, md = _bank(mat, theta)[br]

        def mark(exported, exact, rel="1e-9"):
            return "MATCH" if _cmp(exported, exact, rel) else f"**{exported}**"

        re_m = mark(r["Re_xi"], mp.re(xi))
        im_m = mark(r["Im_xi"], mp.im(xi))
        absx = mp.sqrt(mp.mpf(r["Re_xi"]) ** 2 + mp.mpf(r["Im_xi"]) ** 2)
        ab_m = mark(r["abs_xi"], absx, "1e-8")
        if abs(jz) > mp.mpf("1e-40"):
            jz_m = mark(r["J_z"], jz)
        else:
            jz_m = "MATCH" if abs(mp.mpf(r["J_z"])) <= mp.mpf("1e-40") else \
                f"**{r['J_z']}**"
        cls_ok = r["spatial_class"] == md["spatial_class"]
        if not cls_ok:
            bad += 1
        if any("*" in x for x in (re_m, im_m, ab_m, jz_m)):
            bad += 1
        o = old.get((mat, r["theta_deg"], r["branch"]), {})
        lines.append(
            f"| {mat} | {r['theta_deg']} | {br} | {re_m} | {im_m} | {ab_m} | "
            f"{jz_m} | {'MATCH' if cls_ok else '**' + r['spatial_class'] + '**'} | "
            f"{_short(r['radiation_dir'])} | "
            f"{r['admissible_side']} | {r['outgoing_status']} | "
            f"{o.get('Re_xi', 'n/a')} | {o.get('J_z', 'n/a')} |")

    lines += [
        "",
        "## Result",
        "",
        f"- Rows with any numeric or classification mismatch: **{bad}**",
        "",
        "The `OLD` columns are the point of this report. In the invalidated",
        "file every row of a block repeats one root and one flux; in the",
        "corrected file each row carries its own. For example the PZT-5H block",
        "at 0° shows `OLD Re ξ = +2.569e6` on **every** row including branch 0,",
        "whose true `Re ξ` is `-2.569e6` — a sign error, not a rounding error.",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    print(f"  rows compared : {len(rows)}")
    print(f"  mismatches    : {bad}")


if __name__ == "__main__":
    main()
